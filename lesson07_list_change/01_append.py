# 問題4：input()で追加する
# --------------------------------------------------
# 仲間の名前を3人分入力して、パーティーを作ります。

party = []

for i in range(3):
    name = input("仲間の名前: ")
    party.append(name)

print("パーティー:", party)
print("人数:", len(party))

