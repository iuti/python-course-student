# 問題2：全員を回復したい…けれど？
# --------------------------------------------------
# 3人のHPに、それぞれ10ずつ回復させるつもりのプログラムです。

hps = [50, 20, 80]

for hp in hps:
    hp = hp + 10

print("回復後？:", hps)

# 実行前に予想しましょう。
# 表示されるリスト：
#
# 実行してみよう。リストは変わった？
# hp は「リストの中身をコピーした箱」です。
# コピーを変えても、リストの中身は変わりません。


# --------------------------------------------------
# 問題3：添字を使って書き換える
# --------------------------------------------------
# hps[i] と書くと、リストの中身そのものを書き換えられます。

for i in range(len(hps)):
    hps[i] = hps[i] + 10

print("回復後:", hps)

# 実行前に予想しましょう。
# 表示されるリスト：

# 自力課題：全員のHPを2倍にしてください。
# ここにコードを書きましょう。


