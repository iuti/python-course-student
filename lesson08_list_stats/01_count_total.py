# --------------------------------------------------
# 問題2：条件に合う数を数える
# --------------------------------------------------
# 60点以上の人数を数えます。
# count は「数えるための箱」です。条件に合ったときだけ1増やします。

count = 0

for score in scores:
    if score >= 60:
        count = count + 1

print("60点以上の人数:", count)

