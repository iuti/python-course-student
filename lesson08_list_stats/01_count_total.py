# 第8回 練習1：合計・平均・数える

# 6人のテストの点数です。
scores = [72, 45, 88, 60, 39, 95]


# --------------------------------------------------
# 問題1：合計と平均
# --------------------------------------------------
# 合計は、前回までと同じ方法で計算します。

total = 0

for score in scores:
    total = total + score

print("合計:", total)

# 平均 = 合計 ÷ 人数
# 人数は len(scores) で調べられます。
average = total / len(scores)
print("平均:", average)

