# 第6回 練習1：リストの基本

# 複数の値を [ ] の中にまとめると、リストを作れます。
enemy_hps = [50, 80, 100]

# まずは、リスト全体を表示してみましょう。
print(enemy_hps)


# --------------------------------------------------
# 問題1：要素を取り出す
# --------------------------------------------------
# リストの位置を表す数字を「添字」といいます。
# 添字は0から始まります。

print(enemy_hps[0])
print(enemy_hps[1])
print(enemy_hps[2])

