enemy_hps = [30, 50, 80]

for enemy_hp in enemy_hps:
    print("敵のHP:", enemy_hp)


# --------------------------------------------------
# 問題2：if文と組み合わせる
# --------------------------------------------------
# HPが50以上なら「強敵！」と表示します。

for enemy_hp in enemy_hps:
    if enemy_hp >= 50:
        print(enemy_hp, "強敵！")
    else:
        print(enemy_hp, "通常の敵")


